/** Filters by keyword; an empty query returns everything. */
export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI_LIST.map((e) => e[0]);
  const terms = q.split(/\s+/);
  return EMOJI_LIST.filter(([, words]) => terms.every((t) => words.includes(t))).map((e) => e[0]);
}

/** True when the text contains no letters or digits, i.e. it looks like typed/pasted emoji. */
export function looksLikeEmoji(text: string): boolean {
  const t = text.trim();
  return t.length > 0 && t.length <= 16 && !/[A-Za-z0-9]/.test(t);
}
